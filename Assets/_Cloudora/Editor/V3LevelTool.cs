using System.Collections.Generic;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using Cloudora.Level;
using UnityEditor;
using UnityEngine;
using Debug = UnityEngine.Debug;

namespace Cloudora.Editor
{
    // v3 bölüm aracı — aday raporu: her çerçeve için adayları ölçer, zorluk dağılımını ve hızı raporlar.
    // Bölüm tablosu ve seed seçimi parça parça bunun üzerine kurulacak.
    public static class V3LevelTool
    {
        private const int CandidatesPerFrame = 300;
        private const int MaxStates = 300000;

        private static readonly BoardFrame[] ReportFrames =
        {
            new(4, 2, 2), new(4, 2, 1), new(4, 3, 2), new(4, 3, 1),
            new(5, 3, 2), new(5, 3, 1), new(5, 4, 2), new(6, 4, 2), new(6, 5, 2)
        };

        [MenuItem("Cloudora/V3/Aday Raporu")]
        public static void RunCandidateReport() => WriteReport();

        // Batch: Unity.exe -batchmode -projectPath … -executeMethod Cloudora.Editor.V3LevelTool.RunCandidateReportBatch
        public static void RunCandidateReportBatch()
        {
            bool ok = WriteReport();
            EditorApplication.Exit(ok ? 0 : 1);
        }

        // Kurulmuş parçalar; yeni bir parça tasarlandıkça buraya eklenir.
        private static readonly V3Part[] PartsToBuild = { V3Part.Intro, V3Part.Adaptation };
        private const string DataPath = "Assets/_Cloudora/Scripts/Level/V3LevelData.Generated.cs";

        [MenuItem("Cloudora/V3/Bölüm Verisini Üret")]
        public static void GenerateLevelData()
        {
            WriteLevelData();
            AssetDatabase.ImportAsset(DataPath);
        }

        // Batch: Unity.exe -batchmode -projectPath … -executeMethod Cloudora.Editor.V3LevelTool.GenerateLevelDataBatch
        public static void GenerateLevelDataBatch()
        {
            bool ok;
            try { ok = WriteLevelData(); }
            catch (System.Exception exception)
            {
                Debug.LogError($"CLOUDORA_V3 data generation failed: {exception}");
                ok = false;
            }
            EditorApplication.Exit(ok ? 0 : 1);
        }

        private static bool WriteLevelData()
        {
            var code = new StringBuilder();
            code.Append("// <auto-generated>\r\n");
            code.Append("// Cloudora/V3/Bölüm Verisini Üret ile üretildi — elle değiştirmeyin; araçla yeniden üretin.\r\n");
            code.Append("// Sütunlar: bölüm, bant, kapasite, seed, puan, en kısa çözüm (hamle), tahta, Shuffle yedekleri.\r\n");
            code.Append("// </auto-generated>\r\n");
            code.Append("namespace Cloudora.Level\r\n{\r\n    public static partial class V3LevelData\r\n    {\r\n");
            code.Append("        public static readonly V3Part[] BuiltParts = { ")
                .Append(string.Join(", ", PartsToBuild.Select(p => "V3Part." + p))).Append(" };\r\n\r\n");
            code.Append("        private static readonly V3LevelEntry[] Entries =\r\n        {\r\n");
            foreach (V3Part part in PartsToBuild)
            {
                code.Append($"            // {part}\r\n");
                foreach (V3LevelResult r in V3LevelBuilder.BuildPart(part))
                {
                    DifficultyMetrics m = r.Primary.Result.Metrics;
                    string backups = string.Concat(r.Backups.Select(b => $", \"{V3BoardText.Format(b.Board)}\""));
                    code.Append($"            new V3LevelEntry({r.Level}, DifficultyBand.{r.Band}, {r.Frame.Capacity}, {r.Primary.Seed}, " +
                                $"{r.Primary.Score.ToString("R", CultureInfo.InvariantCulture)}f, {m.OptimalMoves}, " +
                                $"\"{V3BoardText.Format(r.Primary.Board)}\"{backups}),\r\n");
                    Debug.Log($"CLOUDORA_V3 level={r.Level} band={r.Band} frame={r.Frame} window={r.Window} seed={r.Primary.Seed} {m}");
                }
            }
            code.Append("        };\r\n    }\r\n}\r\n");
            File.WriteAllText(DataPath, code.ToString(), new UTF8Encoding(false));
            Debug.Log($"CLOUDORA_V3 data written: {DataPath} parts={string.Join(",", PartsToBuild)}");
            return true;
        }

        // Oyundaki (veri dosyasındaki) bölümleri güncel ölçümle yeniden ölçer — kalibrasyon için.
        [MenuItem("Cloudora/V3/Kalibrasyon Raporu")]
        public static void RunCalibrationReport() => WriteCalibrationReport();

        public static void RunCalibrationReportBatch()
        {
            WriteCalibrationReport();
            EditorApplication.Exit(0);
        }

        private static void WriteCalibrationReport()
        {
            for (int level = 1; level <= V3LevelPlan.LastLevel; level++)
            {
                V3LevelEntry entry = V3LevelData.Find(level);
                if (entry == null) continue;
                DifficultyMetrics m = PuzzleSolver.Solve(entry.CreateBoard(), entry.Capacity, MaxStates).Metrics;
                Debug.Log($"CLOUDORA_V3_CAL level={level} band={entry.Band} board={entry.Board} {m}");
            }
        }

        private static bool WriteReport()
        {
            var csv = new StringBuilder("frame,seed,status,optimal_moves,states,dead_ratio,progress_ratio,trap_ratio,choices,score\n");
            var summary = new StringBuilder();
            bool ok = true;
            foreach (BoardFrame frame in ReportFrames)
            {
                var timer = Stopwatch.StartNew();
                CandidateSelection selection = LevelCandidateSelector.Select(frame, new ScoreWindow(0f, 10000f), 1, CandidatesPerFrame, 0, MaxStates);
                timer.Stop();

                foreach (LevelCandidate c in selection.Measured)
                {
                    DifficultyMetrics m = c.Result.Metrics;
                    csv.AppendLine(string.Join(",", frame, c.Seed, c.Result.Status, m.OptimalMoves, m.ReachableStates,
                        F(m.DeadStateRatio), F(m.ProgressMoveRatio), F(m.TrapMoveRatio), F(m.AverageChoices), F(m.Score)));
                }

                List<LevelCandidate> solved = selection.Measured.Where(c => c.Result.Status == Cloudora.Level.SolveStatus.Solved).ToList();
                string line = $"CLOUDORA_V3 frame={frame} measured={selection.Measured.Count} solved={solved.Count} " +
                              $"unsolvable={selection.Unsolvable} over_limit={selection.LimitExceeded} duplicates={selection.Duplicates} " +
                              $"ms_total={timer.ElapsedMilliseconds} max_states={MaxOf(selection.Measured.Select(c => c.Result.Metrics.ReachableStates))}";
                if (solved.Count > 0)
                {
                    line += $" moves[min/med/max]={Pct(solved, c => c.Result.Metrics.OptimalMoves, 0)}/{Pct(solved, c => c.Result.Metrics.OptimalMoves, 50)}/{Pct(solved, c => c.Result.Metrics.OptimalMoves, 100)}" +
                            $" score[p10/p50/p90/max]={Pct(solved, c => c.Score, 10)}/{Pct(solved, c => c.Score, 50)}/{Pct(solved, c => c.Score, 90)}/{Pct(solved, c => c.Score, 100)}" +
                            $" trap[p50/p90]={Pct(solved, c => c.Result.Metrics.TrapMoveRatio, 50)}/{Pct(solved, c => c.Result.Metrics.TrapMoveRatio, 90)}";
                }
                else ok = false;
                summary.AppendLine(line);
                Debug.Log(line);
            }

            string directory = Path.Combine(Directory.GetCurrentDirectory(), "Logs");
            Directory.CreateDirectory(directory);
            File.WriteAllText(Path.Combine(directory, "v3-candidates.csv"), csv.ToString());
            File.WriteAllText(Path.Combine(directory, "v3-candidate-summary.txt"), summary.ToString());
            Debug.Log($"CLOUDORA_V3 report written to {directory} ok={ok}");
            return ok;
        }

        private static string F(float value) => value.ToString("0.###", CultureInfo.InvariantCulture);
        private static int MaxOf(IEnumerable<int> values) => values.DefaultIfEmpty(0).Max();

        private static string Pct(List<LevelCandidate> items, System.Func<LevelCandidate, float> value, int percentile)
        {
            float[] sorted = items.Select(value).OrderBy(v => v).ToArray();
            int index = Mathf.Clamp(Mathf.RoundToInt((sorted.Length - 1) * percentile / 100f), 0, sorted.Length - 1);
            return F(sorted[index]);
        }
    }
}
